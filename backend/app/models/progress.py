import uuid
from datetime import datetime
from app.core.dbtypes import UtcDateTime
from sqlalchemy import (
    Column,
    String,
    Integer,
    Boolean,
    Text,
    ForeignKey,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import UUID

from app.core.database import Base


class LectureProgress(Base):
    """One row per (student, lecture): completion state and where they stopped."""

    __tablename__ = "lecture_progress"
    __table_args__ = (UniqueConstraint("user_id", "lecture_id", name="uq_progress_user_lecture"),)

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    lecture_id = Column(String(64), nullable=False)
    completed = Column(Boolean, default=False, nullable=False)
    completed_at = Column(UtcDateTime, nullable=True)
    position = Column(Integer, default=0, nullable=False)  # seconds into the video
    duration = Column(Integer, default=0, nullable=False)  # seconds, 0 = unknown
    updated_at = Column(UtcDateTime, default=datetime.utcnow, nullable=False)


class LectureNote(Base):
    __tablename__ = "lecture_notes"
    __table_args__ = (UniqueConstraint("user_id", "lecture_id", name="uq_note_user_lecture"),)

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    lecture_id = Column(String(64), nullable=False)
    content = Column(Text, default="", nullable=False)
    updated_at = Column(UtcDateTime, default=datetime.utcnow, nullable=False)


class StudyPlan(Base):
    __tablename__ = "study_plans"

    # The id is generated by the client so a retried request can never create a duplicate.
    id = Column(String(64), primary_key=True)
    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    date_key = Column(String(10), nullable=False)  # YYYY-MM-DD in the student's own timezone
    title = Column(String(200), nullable=False)
    time = Column(String(40), nullable=True)
    source = Column(String(10), default="manual", nullable=False)  # manual | auto
    created_at = Column(UtcDateTime, default=datetime.utcnow, nullable=False)


class StudyActivity(Base):
    """A day on which the student did something. Streaks are counted from these."""

    __tablename__ = "study_activity"
    __table_args__ = (UniqueConstraint("user_id", "day", name="uq_activity_user_day"),)

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    day = Column(String(10), nullable=False)
